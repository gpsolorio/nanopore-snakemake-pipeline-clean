##############################################################################
# run_bsmooth.R — Whole-genome BSmooth + per-sample DMR beta extraction
##############################################################################

suppressPackageStartupMessages({
  library(bsseq)
  library(DSS)
  library(GenomicRanges)
  library(BiocParallel)
  library(data.table)
  library(glue)
})


# ============================================================================
# 1. CLI Arguments
# ============================================================================

args <- commandArgs(trailingOnly = TRUE)

get_arg <- function(args, flag, default = NULL) {
  i <- which(args == flag)
  if (length(i) == 0) return(default)
  args[i + 1]
}

repo_root    <- get_arg(args, "--repo_root")
metadata_tsv <- get_arg(args, "--metadata")
dmr_file     <- get_arg(args, "--dmr_file")
out_txt      <- get_arg(args, "--out_txt")
out_bed      <- get_arg(args, "--out_bed")
threads      <- as.integer(get_arg(args, "--threads", "4"))
group_col    <- get_arg(args, "--group_col", "diagnosis")
group_labels <- get_arg(args, "--group_labels", NA_character_)  # e.g. "ASD,TD"; NA = keep all non-NA values in group_col

if (is.null(repo_root))    stop("--repo_root is required")
if (is.null(metadata_tsv)) stop("--metadata is required")
if (is.null(dmr_file))     stop("--dmr_file is required")
if (is.null(out_txt))      stop("--out_txt is required")
if (is.null(out_bed))      stop("--out_bed is required")

config_dir <- file.path(repo_root, "analysis", "dmr", "config")
source(file.path(config_dir, "utils.R"))
source(file.path(config_dir, "params.R"))
# NOTE: datasets.R no longer sourced — sample info comes from metadata TSV

print_config("dss_smooth_betas", list(
  metadata = metadata_tsv,
  dmr_file = dmr_file,
  out_txt  = out_txt,
  out_bed  = out_bed,
  threads  = threads
))


# ============================================================================
# 2. Load sample metadata from TSV
# ============================================================================

meta <- read.table(metadata_tsv, header = TRUE, sep = "\t",
                   stringsAsFactors = FALSE, colClasses = "character")

if (!group_col %in% colnames(meta)) {
  stop(glue("Metadata TSV is missing group column: {group_col}",
            " (use --group_col to point at the correct column)"))
}

# Determine which values of group_col define the two (or more) groups.
# --group_labels lets the caller restrict to specific labels (e.g. "ASD,TD");
# otherwise every non-missing value present in group_col is used as-is,
# so this works for arbitrary cohorts (trios, case/control, etc.) without
# hardcoding any particular study's label scheme.
if (!is.na(group_labels)) {
  wanted <- trimws(strsplit(group_labels, ",")[[1]])
  meta   <- meta[meta[[group_col]] %in% wanted, ]
} else {
  meta <- meta[!is.na(meta[[group_col]]) & meta[[group_col]] != "", ]
}

if (nrow(meta) == 0) {
  stop(glue("No samples found in metadata TSV for group column '{group_col}'",
            if (!is.na(group_labels)) glue(" with labels: {group_labels}") else ""))
}

# Use the BED paths generated by Snakemake
if (!"bed_path" %in% colnames(meta)) {
  stop("Metadata TSV is missing required column: bed_path")
}

ds <- list(
  sample_names = meta$sample_id,
  groups       = meta[[group_col]],
  bed_paths    = meta$bed_path
)

cat(glue("\n[BSmooth] {length(ds$sample_names)} samples loaded (grouped by '{group_col}')\n"))
for (g in unique(ds$groups)) {
  cat(glue("[BSmooth] {g}: {paste(ds$sample_names[ds$groups == g], collapse=', ')}\n"))
}
cat("\n")


# ============================================================================
# 3-4. Read modkit BEDs -> coverage-filtered BSseq object
# ============================================================================

BSobj <- build_bsseq_from_metadata(
  bed_paths       = ds$bed_paths,
  sample_names    = ds$sample_names,
  groups          = ds$groups,
  coverage_params = COVERAGE
)

# Keep sample_names in sync in case build_bsseq_from_metadata() dropped any
ds$sample_names <- ds$sample_names[ds$sample_names %in% colnames(BSobj)]


# ============================================================================
# 5. BSmooth — Whole-Genome Smoothing
# ============================================================================

cat(glue("[BSmooth] Smoothing with {threads} workers ",
         "(ns=70, h=1000, maxGap=1e8)...\n\n"))

BSobj_smoothed <- BSmooth(
  BSobj,
  ns      = 70,
  h       = 1000,
  maxGap  = 10^8,
  BPPARAM = MulticoreParam(workers = threads, progressbar = TRUE),
  verbose = TRUE
)

cat("\n[BSmooth] Smoothing complete\n\n")


# ============================================================================
# 6. Import DMR GRanges
# ============================================================================

cat(glue("[BSmooth] Loading DMRs from {dmr_file}\n\n"))

if (!file.exists(dmr_file) || file.size(dmr_file) == 0) {
  stop("DMR file missing or empty: cannot proceed with BSmooth")
}

dmrs <- tryCatch(
  read.csv(dmr_file, header = TRUE),
  error = function(e) {
    stop("DMR file is not a valid CSV: ", conditionMessage(e))
  }
)

dmr_gr <- makeGRangesFromDataFrame(
  dmrs,
  keep.extra.columns = TRUE,
  ignore.strand      = TRUE,
  seqnames.field     = "chr",
  start.field        = "start",
  end.field          = "end"
)

cat(glue("[BSmooth] {length(dmr_gr)} DMRs imported\n\n"))


# ============================================================================
# 7. Extract Per-Sample Smoothed Betas
# ============================================================================

cat("[BSmooth] Extracting per-sample smoothed methylation values...\n\n")

smoothed_betas <- getMeth(
  BSobj_smoothed,
  regions = dmr_gr,
  type    = "smooth",
  what    = "perRegion"
)

colnames(smoothed_betas) <- ds$sample_names


# ============================================================================
# 8. Save Outputs
# ============================================================================

dir.create(dirname(out_txt), showWarnings = FALSE, recursive = TRUE)
dir.create(dirname(out_bed), showWarnings = FALSE, recursive = TRUE)

output_txt <- data.frame(
  chr   = as.character(seqnames(dmr_gr)),
  start = start(dmr_gr),
  end   = end(dmr_gr),
  smoothed_betas,
  check.names = FALSE
)

write.table(output_txt, out_txt,
  sep       = "\t",
  quote     = FALSE,
  row.names = FALSE,
  col.names = TRUE
)
cat(glue("[BSmooth] Plain text written to {out_txt}\n"))

output_bed <- data.frame(
  "#chr"       = as.character(seqnames(dmr_gr)),
  start        = start(dmr_gr) - 1L,
  end          = end(dmr_gr),
  phenotype_id = paste0(seqnames(dmr_gr), ":", start(dmr_gr), "-", end(dmr_gr)),
  smoothed_betas,
  check.names  = FALSE
)

write.table(output_bed, out_bed,
  sep       = "\t",
  quote     = FALSE,
  row.names = FALSE,
  col.names = TRUE
)
cat(glue("[BSmooth] tensorQTL BED written to {out_bed}\n"))
cat(glue("\n[BSmooth] Done. {nrow(output_bed)} DMRs x {length(ds$sample_names)} samples\n"))
