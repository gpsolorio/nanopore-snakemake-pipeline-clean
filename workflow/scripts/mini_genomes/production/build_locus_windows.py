#!/usr/bin/env python3
"""
build_locus_windows.py

Reads a gene-locus BED (like your methylartist regions file) and
prints out Window(...) entries -- ready to paste into window_spec.py's
LOCUS_WINDOWS list -- that fully contain each gene plus a flank on
each side, so downstream annotation BEDs (CpG islands etc.) that sit
just outside the gene body still land inside the window.

Usage:
    python build_locus_windows.py <genes.bed> [flank_bp]

flank_bp defaults to 5000. Windows are NOT merged even if they'd
overlap each other -- each gene gets its own mini-contig, named after
column 4 of the BED, so plots/labels stay unambiguous.
"""
import sys

DEFAULT_FLANK = 5_000


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)
    bed_path = sys.argv[1]
    flank = int(sys.argv[2]) if len(sys.argv) > 2 else DEFAULT_FLANK

    print("# Generated by build_locus_windows.py -- paste into window_spec.py LOCUS_WINDOWS")
    print("# Each contig is the gene body plus a", flank, "bp flank on each side.")
    total_bp = 0
    with open(bed_path) as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith("#") or line.startswith("track"):
                continue
            fields = line.split("\t")
            chrom, start0, end0, name = fields[0], int(fields[1]), int(fields[2]), fields[3]

            hg38_start = max(1, start0 + 1 - flank)   # 1-based
            hg38_end = end0 + flank
            seq = hg38_end - hg38_start + 1
            total_bp += seq

            print(
                f'    Window("{chrom}", {seq}, hg38_start={hg38_start}, '
                f'mini_name="{name}_locus", spans=[(1, {seq}, "hi")]),'
            )
    print(f"# total added: {total_bp:,} bp across all loci", file=sys.stderr)


if __name__ == "__main__":
    main()
